# 字符 n-gram 的长度。
# 中文没有天然的空格分词，长度为 2 的 n-gram（二元组）既能保留局部语序，
# 又比单个汉字更能表达语义，是中文查重里常用的折中方案。
N_GRAM_SIZE = 2

# 答案文件保留的小数位数。
DECIMAL_PLACES = 2

# 是否把相似度输出成百分数（0~100）。
# 需求只说"浮点型，精确到小数点后两位"，没有明确是 0~1 还是 0~100。
# 默认输出 0~1 的相似度；如果评测给出的答案用的是百分数，把这里改成 True 即可。
OUTPUT_AS_PERCENTAGE = False
